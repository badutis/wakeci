"""The key tables of docs/configuration.md, written from docs/config.schema.json, so the
reference never drifts from what ``wakeci check`` and editors apply.

    python3 scripts/config_reference.py          rewrite the tables in docs/configuration.md
    python3 scripts/config_reference.py --check  exit 1 if they are out of date (CI, tests)

The tables sit between the START and END markers; everything else in the page is prose.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "docs" / "config.schema.json"
PAGE = ROOT / "docs" / "configuration.md"
START = "<!-- The tables below are generated by scripts/config_reference.py from config.schema.json. -->"
END = "<!-- End of the generated tables. -->"
HIDDEN = {"$schema"}  # described in the prose


def _value(v) -> str:
    if v is None:
        return "—"
    return f"`{json.dumps(v)}`" if not isinstance(v, str) else f"`{v}`"


def _table(title: str, schema: dict) -> str:
    required = set(schema.get("required", []))
    rows = [f"**{title}**", "", "| Key | Required | Default | Meaning |", "|---|---|---|---|"]
    for key, prop in schema["properties"].items():
        if key in HIDDEN:
            continue
        # "<address>" would be read as an HTML tag; "|" would end the cell.
        meaning = prop["description"].replace("<", "&lt;").replace(">", "&gt;").replace("|", "\\|")
        default = _value(prop.get("default"))
        rows.append(f"| `{key}` | {'yes' if key in required else ''} | {default} | {meaning} |")
    return "\n".join(rows)


def tables(schema: dict) -> str:
    props = schema["properties"]
    return "\n\n".join(
        [
            _table("The file", schema),
            _table("A source (`sources[]`)", props["sources"]["items"]),
            _table("A machine (`machines[]`)", props["machines"]["items"]),
            _table("Notifications (`notify`)", props["notify"]),
        ]
    )


def render(page: str, schema: dict) -> str:
    before, rest = page.split(START, 1)
    _, after = rest.split(END, 1)
    return f"{before}{START}\n\n{tables(schema)}\n\n{END}{after}"


def main(argv: list) -> int:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    page = PAGE.read_text(encoding="utf-8")
    new = render(page, schema)
    if argv == ["--check"]:
        if new != page:
            print("docs/configuration.md is out of date: run python3 scripts/config_reference.py", file=sys.stderr)
            return 1
        return 0
    if argv:
        print(__doc__, file=sys.stderr)
        return 2
    PAGE.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
